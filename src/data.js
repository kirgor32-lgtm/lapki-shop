const prep = (list, b) => list.map((p) => ({
  ...p, id: `${b.pre}-${p.id}`, slug: `${b.slug}-${p.slug}`, brand: b.name, line: b.name,
  animal: p.kind, cat: 'dry', code: p.code || '', bg: '',
}))
